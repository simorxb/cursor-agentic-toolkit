% DESIGN_CONTROLLER Design discrete stabilizing controller for unstable plant
%
% Plant: P(s) = 1/(s^2 - 0.1*s + 1)
% Requirements:
%   - closed-loop stability
%   - sensitivity margin Sm = 1/Ms > 0.5
%   - rise time < 1 s
%   - overshoot < 10%
%   - |y(t) - 1| <= 0.02 for all t >= 2 s (after unit step)
%   - digital controller, Ts = 0.1 s
%   - prefer smooth control effort (reduced setpoint kick)
%
% Architecture: discrete 2-DOF PIDF (setpoint weights b, c).

close all
clc

%% Plant
s = tf('s');
P = 1 / (s^2 - 0.1*s + 1);
Ts = 0.1;
Pd = c2d(P, Ts, 'zoh');

%% 2-DOF discrete PIDF — softened control effort
% Start from pidtune PM=50°, then detune proportional/derivative action and
% lower setpoint weights (especially c) to cut the step kick on u while
% still meeting Sm, tr, Mp, and the 2 s ±2% envelope.
opts = pidtuneOptions('PhaseMargin', 50, 'DesignFocus', 'reference-tracking');
C0 = pidtune(Pd, 'PIDF2', opts);
C = C0;
C.Kp = C0.Kp * 0.75;
C.Kd = C0.Kd * 0.65;
C.Tf = 0.08;
C.b = 0.9;
C.c = 0.05;

%% Closed-loop analysis
T = getPIDLoopResponse(C, Pd, 'closed-loop');
Tu = getPIDLoopResponse(C, Pd, 'controller-effort');
L = getPIDLoopResponse(C, Pd, 'open-loop');
S = feedback(1, L);
info = stepinfo(T);
Ms = getPeakGain(S);
Sm = 1 / Ms;
[Gm, Pm] = margin(L);

tgrid = (0:Ts:20)';
[ygrid, ty] = step(T, tgrid);
[ugrid, ~] = step(Tu, tgrid);
band = 0.02;
tSettle = 2;
inBand = all(abs(ygrid(ty >= tSettle) - 1) <= band);
yminAfter = min(ygrid(ty >= tSettle));
ymaxAfter = max(ygrid(ty >= tSettle));
uPeak = max(abs(ugrid));

fprintf('Controller design summary\n');
fprintf('  Stable:              %d\n', isstable(T));
fprintf('  Rise time:           %.3f s  (req < 1)\n', info.RiseTime);
fprintf('  Overshoot:           %.2f %% (req < 10)\n', info.Overshoot);
fprintf('  Settling time:       %.2f s\n', info.SettlingTime);
fprintf('  In +/-2%% for t>=2s: %d  (range [%.4f, %.4f])\n', inBand, yminAfter, ymaxAfter);
fprintf('  Sensitivity margin:  %.3f    (req > 0.5)\n', Sm);
fprintf('  Ms:                  %.3f\n', Ms);
fprintf('  Gain margin:         %.2f dB\n', mag2db(Gm));
fprintf('  Phase margin:        %.2f deg\n', Pm);
fprintf('  Peak |u|:            %.2f\n', uPeak);
fprintf('  PIDF2: Kp=%.6f Ki=%.6f Kd=%.6f Tf=%.6f b=%.6f c=%.6f\n', ...
    C.Kp, C.Ki, C.Kd, C.Tf, C.b, C.c);

assert(isstable(T), 'Closed-loop unstable');
assert(info.RiseTime < 1, 'Rise time requirement failed');
assert(info.Overshoot < 10, 'Overshoot requirement failed');
assert(Sm > 0.5, 'Sensitivity margin requirement failed');
assert(inBand, 'Settling band requirement failed (|y-1|<=2%% for t>=2s)');

%% Export parameters for Simulink
Kp = C.Kp;
Ki = C.Ki;
Kd = C.Kd;
Tf = C.Tf;
b = C.b;
c = C.c;
P_num = 1;
P_den = [1, -0.1, 1];

metrics = struct( ...
    'RiseTime', info.RiseTime, ...
    'Overshoot', info.Overshoot, ...
    'SettlingTime', info.SettlingTime, ...
    'InBandAfter2s', inBand, ...
    'YminAfter2s', yminAfter, ...
    'YmaxAfter2s', ymaxAfter, ...
    'UPeak', uPeak, ...
    'Sm', Sm, ...
    'Ms', Ms, ...
    'GainMargin_dB', mag2db(Gm), ...
    'PhaseMargin_deg', Pm);

outDir = fileparts(fileparts(mfilename('fullpath')));
save(fullfile(outDir, 'controller_design.mat'), ...
    'P', 'Pd', 'C', 'Ts', ...
    'Kp', 'Ki', 'Kd', 'Tf', 'b', 'c', ...
    'P_num', 'P_den', 'metrics');

initPath = fullfile(outDir, 'scripts', 'init_controller_params.m');
fid = fopen(initPath, 'w');
fprintf(fid, '%% Auto-generated by design_controller.m — do not edit by hand\n');
fprintf(fid, 'Ts = %.12g;\n', Ts);
fprintf(fid, 'Kp = %.12g;\n', Kp);
fprintf(fid, 'Ki = %.12g;\n', Ki);
fprintf(fid, 'Kd = %.12g;\n', Kd);
fprintf(fid, 'Tf = %.12g;\n', Tf);
fprintf(fid, 'b = %.12g;\n', b);
fprintf(fid, 'c = %.12g;\n', c);
fprintf(fid, 'P_num = [%s];\n', sprintf('%.12g ', P_num));
fprintf(fid, 'P_den = [%s];\n', sprintf('%.12g ', P_den));
fclose(fid);

fprintf('Saved controller_design.mat and scripts/init_controller_params.m\n');
